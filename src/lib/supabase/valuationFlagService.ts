export async function createManualFlag(payload: {
  collateralId: string;
  flagType: ValuationFlagType;
  severity: ValuationFlagSeverity;
  title: string;
  description?: string;
  daysOverdue?: number;
  theoreticalValue?: number;
  pricingMethodUsed?: PricingMethod;
  ltvImpactNote?: string;
  createdBy?: string;
}): Promise<ValuationPricingFlag> {
  const supabase = createClient();
  const { data, error } = await supabase
    .from('valuation_pricing_flags')
    .insert({
      collateral_id: payload.collateralId,
      flag_type: payload.flagType,
      severity: payload.severity,
      title: payload.title,
      description: payload.description ?? null,
      days_overdue: payload.daysOverdue ?? 0,
      theoretical_value: payload.theoreticalValue ?? null,
      pricing_method_used: payload.pricingMethodUsed ?? 'theoretical',
      ltv_impact_note: payload.ltvImpactNote ?? null,
      auto_generated: false,
      created_by: payload.createdBy ?? null,
      flag_status: 'open',
    })
    .select(`
      *,
      collateral_records(description, collateral_type),
      acknowledged_profile:user_profiles!acknowledged_by(full_name),
      resolved_profile:user_profiles!resolved_by(full_name)
    `)
    .single();
  if (error) throw error;
  return rowToFlag(data);
}

// ─── Auto-detection: scan overdue valuations and create flags ─────────────────
export async function scanAndCreateOverdueFlags(createdBy?: string): Promise<number> {
  const supabase = createClient();
  const today = new Date().toISOString().split('T')[0];

  // Find overdue valuations not yet flagged
  const { data: overdueValuations, error } = await supabase
    .from('collateral_valuations')
    .select('id, collateral_id, scheduled_date, valuation_status, collateral_records(description)')
    .in('valuation_status', ['Overdue', 'Scheduled'])
    .lt('scheduled_date', today);

  if (error) throw error;
  if (!overdueValuations?.length) return 0;

  let created = 0;
  for (const v of overdueValuations) {
    // Check if open flag already exists for this valuation
    const { data: existing } = await supabase
      .from('valuation_pricing_flags')
      .select('id')
      .eq('valuation_id', v.id)
      .eq('flag_status', 'open')
      .maybeSingle();

    if (existing) continue;

    const daysOverdue = Math.ceil(
      (new Date().getTime() - new Date(v.scheduled_date).getTime()) / (1000 * 60 * 60 * 24)
    );
    const severity: ValuationFlagSeverity =
      daysOverdue > 90 ? 'critical' : daysOverdue > 30 ? 'high' : daysOverdue > 14 ? 'medium' : 'low';

    await supabase.from('valuation_pricing_flags').insert({
      collateral_id: v.collateral_id,
      valuation_id: v.id,
      flag_type: 'overdue_valuation',
      flag_status: 'open',
      severity,
      title: `Valuation Overdue — Theoretical Pricing Active`,
      description: `Scheduled valuation (due ${v.scheduled_date}) has not been completed. LTV is using theoretical pricing.`,
      days_overdue: daysOverdue,
      last_valuation_date: v.scheduled_date,
      pricing_method_used: 'theoretical',
      ltv_impact_note: `LTV may be inaccurate by up to ${Math.min(daysOverdue / 10, 15).toFixed(0)}% due to ${daysOverdue} days without valuation.`,
      auto_generated: true,
      created_by: createdBy ?? null,
    });
    created++;
  }
  return created;
}
